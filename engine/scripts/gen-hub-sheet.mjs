#!/usr/bin/env node
// Generate neo-hence's web/src/lib/megapot-campaign.ts from campaign.json.
//
//   node engine/scripts/gen-hub-sheet.mjs [campaign.json] > /path/to/neo-hence/web/src/lib/megapot-campaign.ts
//   npm --prefix engine run gen:hub-sheet > ...
//
// The hub sheet used to be hand-synced under a "GENERATED" banner. This makes the banner true.
// Rules (keep them boring, the hub type-checks against the output):
//   - every `$`-prefixed key is an ops note and is stripped, recursively
//   - engine-only sections are dropped: opsGrants (ops credit grants), caps.globalBudgetUsdc
//     (spend safety stop, set per deploy), multiplierBonus (engine pool cap), $doc
//   - `campaign.*`, `eligibility.*`, `economics.*` and `caps.*` are flattened to the top level,
//     which is the shape RewardHub reads (el.startMs, el.feeBps, el.ticketsPerWalletPerDay, ...)
//   - `hub.*` (hub-only overlay: marketingConsentDefault, engineCycleS) is merged at the top level
//   - `testReset` and `retro` pass through (the hub reads resetEpoch, and retro when present)
//   - the three symbol arrays carry `as string[]` so an empty list does not infer never[]
// No dependencies. Output is deterministic for a given campaign.json (the header carries its sha256).
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const file = resolve(process.argv[2] || resolve(here, '../../campaign.json'));
const raw = readFileSync(file);
const sha = createHash('sha256').update(raw).digest('hex');
const src = JSON.parse(raw.toString('utf8'));

const strip = (v) => {
  if (Array.isArray(v)) return v.map(strip);
  if (v && typeof v === 'object') {
    const o = {};
    for (const [k, x] of Object.entries(v)) if (!k.startsWith('$')) o[k] = strip(x);
    return o;
  }
  return v;
};
const c = strip(src);
const need = (obj, k, where) => { if (obj?.[k] === undefined) throw new Error(`campaign.json: missing ${where}.${k}`); return obj[k]; };

// ----- assemble, in the order the hub file has always had -----------------------------------
const out = {};
out.id = need(c.campaign, 'id', 'campaign');
out.name = need(c.campaign, 'name', 'campaign');
out.network = need(c.campaign, 'network', 'campaign');
out.startMs = need(c.campaign, 'startMs', 'campaign');
out.tierSinceMs = need(c.campaign, 'tierSinceMs', 'campaign');
out.endMs = need(c.campaign, 'endMs', 'campaign');
out.products = need(c.eligibility, 'products', 'eligibility');
out.symbols = need(c.eligibility, 'symbols', 'eligibility');
out.excludeZeroFeePairs = c.eligibility.excludeZeroFeePairs ?? [];
out.feeBps = need(c.economics, 'feeBps', 'economics');
out.rolloverShare = need(c.economics, 'rolloverShare', 'economics');
out.ticketsPerWalletPerDay = need(c.caps, 'ticketsPerWalletPerDay', 'caps');
out.ticketsPerWalletPerWeek = need(c.caps, 'ticketsPerWalletPerWeek', 'caps');
out.multipliers = need(c, 'multipliers', 'root');
out.testReset = need(c, 'testReset', 'root');
out.requireBuilderFee = need(c, 'requireBuilderFee', 'root');
out.streakBox = need(c, 'streakBox', 'root');
out.firstTradeBonus = need(c, 'firstTradeBonus', 'root');
for (const [k, v] of Object.entries(c.hub || {})) out[k] = v;       // hub overlay -> top level
if (out.marketingConsentDefault === undefined) throw new Error('campaign.json: hub.marketingConsentDefault is required');
if (out.engineCycleS === undefined) throw new Error('campaign.json: hub.engineCycleS is required');
out.terms = need(c, 'terms', 'root');
if (c.retro) out.retro = c.retro;
if (c.riskCohort) out.riskCohort = c.riskCohort;   // hub shows the cohort's first-mint bar to the wallets it applies to

// ----- emit ---------------------------------------------------------------------------------
const iso = (ms) => new Date(ms).toISOString().replace('.000Z', 'Z');
const num = (n) => (Number.isInteger(n) && /\.0$/.test(String(n)) ? String(n) : JSON.stringify(n));
// keep 4.0 / 1.0 as written in the JSON so the hub diff stays quiet
const numLiteral = (key) => {
  const m = raw.toString('utf8').match(new RegExp(`"${key}":\\s*(-?[0-9.]+)`));
  return m ? m[1] : null;
};
const lines = [];
lines.push(`/* GENERATED by megapot-fee-accrual/engine/scripts/gen-hub-sheet.mjs from campaign.json (sha ${sha}) — do not edit`);
lines.push(`   Edit campaign.json in Hence-Markets/megapot-fee-accrual and regenerate:`);
lines.push(`     npm --prefix engine run gen:hub-sheet > <neo-hence>/web/src/lib/megapot-campaign.ts`);
lines.push(`   Window: ${iso(out.startMs)} .. ${iso(out.endMs)} · network ${out.network} */`);
lines.push('export const CAMPAIGN = {');
const comments = {
  startMs: `// ${iso(out.startMs)} (Season 1 go-live)`,
  tierSinceMs: `// ${iso(out.tierSinceMs)} - multiplier tiers count basket volume from the ORIGINAL season start; startMs still governs which fills earn credit`,
  endMs: `// ${iso(out.endMs)}`,
  products: `// 'spot' = Robinhood Chain swaps; the engine credits their EXACT recorded app fee (campaign.json $spotNote)`,
  testReset: `/* team-test reset: when resetEpoch changes, the hub wipes its per-wallet markers once */`,
  streakBox: `/* DAILY STREAK BOX - the engine rolls this matrix per distinct $minDayUsd trade day; lib/streak-box.ts mirrors it */`,
  firstTradeBonus: `/* activation pack: 1-5 tickets drawn without replacement from a fixed season pool; the engine holds the depleting slot counts, the client can only show the range */`,
  marketingConsentDefault: `/* consent box default; false = unticked (EU rules, Planet49) */`,
  engineCycleS: `/* engine cadence (ENGINE_INTERVAL_S): buys land within one cycle of a threshold crossing */`,
  terms: `/* user-facing rules - rendered by the Terms sheet, retuned per season */`,
  retro: `/* Megapot's 12 tickets/day in the pool wallet are handed to users (active round) before USDC buys */`,
};
const stringArrays = new Set(['products', 'symbols', 'excludeZeroFeePairs']);
for (const [k, v] of Object.entries(out)) {
  const cm = comments[k];
  if (cm && cm.startsWith('/*')) lines.push(`  ${cm}`);
  let val;
  if (stringArrays.has(k)) val = `${JSON.stringify(v)} as string[]`;
  else if (typeof v === 'number') val = numLiteral(k) ?? num(v);
  else if (typeof v === 'object' && v !== null && !Array.isArray(v) && Object.keys(v).length <= 2 && !['streakBox', 'terms'].includes(k)) val = JSON.stringify(v);
  else if (typeof v === 'object' && v !== null) val = JSON.stringify(v, null, 2).split('\n').map((l, i) => (i ? '  ' + l : l)).join('\n');
  else val = JSON.stringify(v);
  const trail = cm && cm.startsWith('//') ? `   ${cm}` : '';
  lines.push(`  ${k}: ${val},${trail}`);
}
lines.push('};');
process.stdout.write(lines.join('\n') + '\n');
